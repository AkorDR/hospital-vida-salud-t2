CREATE TABLE IF NOT EXISTS citas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    especialidad VARCHAR(100) NOT NULL,
    fecha_hora TIMESTAMP WITH TIME ZONE NOT NULL,
                             profesional_codigo VARCHAR(50) NOT NULL,
    motivo VARCHAR(250) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL
    DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_cita_estado CHECK (
        estado IN (
            'PENDIENTE', 'CONFIRMADA', 'ATENDIDA',
            'CANCELADA', 'AUSENTE'
        )
    )
    );

CREATE UNIQUE INDEX IF NOT EXISTS uk_cita_profesional_horario
    ON citas (profesional_codigo, fecha_hora)
    WHERE estado <> 'CANCELADA';

CREATE UNIQUE INDEX IF NOT EXISTS uk_cita_paciente_horario
    ON citas (paciente_id, fecha_hora)
    WHERE estado <> 'CANCELADA';